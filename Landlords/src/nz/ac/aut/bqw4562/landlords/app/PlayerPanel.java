package nz.ac.aut.bqw4562.landlords.app;

import java.awt.*;
import javax.swing.*;
import nz.ac.aut.bqw4562.landlords.player.Player;

/**
 *
 * @author AngelaSoriano
 * Panel displays Player Name, player Deck
 * Uses GridLayout, three rows, playerName at top, deck on the bottom
 */
public class PlayerPanel extends JPanel{
    //References needed for this panel
    private Player playerOwner;
    
    //constants for panel weight
    private final double PLAYER_NAME_WEIGHT = 0.1;
    private final double DECK_PANEL_WEIGHT = 0.9;
    
    //Components needed for this panel
    private JPanel deckPanelHolder = new JPanel(new BorderLayout());
    private DeckPanel deckPanel;
    private JLabel playerName;
    
    public PlayerPanel(Player player){
        
        playerOwner = player;
        
        //gridbaglayout for combining deck and player name
        setLayout(new GridBagLayout());
        GridBagConstraints gbc = new GridBagConstraints();
        //stretch horizontally and vertically, fill 100% of width
        gbc.fill = GridBagConstraints.BOTH;
        gbc.gridx = 0;
        gbc.weightx = 1;
        
        //set JLabel to be players name
        playerName = new JLabel("Player playing: " + playerOwner.getPlayerName());
        
        //create deckPanel using player's deck
        deckPanel = new DeckPanel(player.getPlayerDeck());
        
        //adding components
        gbc.gridy = 0;
        gbc.weighty = PLAYER_NAME_WEIGHT;
        add(playerName, gbc);
        
        gbc.gridy++;
        gbc.weighty = DECK_PANEL_WEIGHT;
        add(deckPanelHolder, gbc);
        
        //sets preferredSize, generated by Gemini
        deckPanelHolder.setPreferredSize(new Dimension(0, 0));
        playerName.setPreferredSize(new Dimension(0, 0));
    }
    
    //empty constructor as placeholder
    public PlayerPanel(){
    }
    
    public void displayPlayer(){
        this.revalidate();
        this.repaint();
    }
    
    //adapted from code block in GamePanel
    public void displayPlayerDeck() {
        if (deckPanel != null) {
            deckPanel.displayDeck();

            deckPanelHolder.removeAll();
            deckPanelHolder.add(deckPanel, BorderLayout.CENTER);
            deckPanelHolder.revalidate();
            deckPanelHolder.repaint();
        }
    }
    
    //getter for playerOwner;
    public Player getOwner(){
        return playerOwner;
    }
    
}
