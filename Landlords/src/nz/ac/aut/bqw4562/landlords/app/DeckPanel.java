package nz.ac.aut.bqw4562.landlords.app;

import java.awt.*;
import javax.swing.*;
import nz.ac.aut.bqw4562.landlords.cards.Card;
import nz.ac.aut.bqw4562.landlords.cards.Deck;

/**
 *
 * @author AngelaSoriano
 * Panel displays the deck using grid layout
 */
public class DeckPanel extends JPanel{
    //Reference needed
    Deck deck;
    
    public DeckPanel(Deck deck){
        this.deck = deck;
        setLayout(new GridLayout(0, 5,5 , 5));
    }
    
    //displays contents of deck using printDeck,
    public void displayDeck(){
        removeAll();
        
        for (Card card : deck.getDeck()){
            CardButton cardButton = new CardButton(card);
            
            //generated by Gemini
            cardButton.addActionListener(e -> {
            CardButton clickedButton = (CardButton) e.getSource();
            Card clickedCard = clickedButton.getCard();
            
            // Handle the card click (e.g., select it or play it)
            clickedButton.toggleSelection();
            System.out.println("Clicked card: " + clickedCard);
            });
            
            add(cardButton);
        }
                    
        this.revalidate();
        this.repaint();
    }
}
