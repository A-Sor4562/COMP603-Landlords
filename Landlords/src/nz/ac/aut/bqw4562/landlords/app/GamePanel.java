package nz.ac.aut.bqw4562.landlords.app;

import java.awt.*;
import java.util.ArrayList;
import java.util.List;
import javax.swing.*;
import nz.ac.aut.bqw4562.landlords.game.Game;
import static nz.ac.aut.bqw4562.landlords.game.Game.getGameInstance;

/**
 *
 * @author AngelaSoriano
 * Class is the main panel for the actual game, is also a cardLayout which changes
 * in between phases
 * grid layout where the player panel is displayed on the bottom
 */
public class GamePanel extends JPanel{
    Game game = getGameInstance();
    private JPanel phases;
    private CardLayout cardLayout;
    
    //constants for panel weight
    private final double PHASE_PANEL_WEIGHT = 0.6;
    private final double PLAYER_PANEL_WEIGHT = 0.4;
    
    //Holds panel of currentPlayer
    private JPanel playerPanelHolder = new JPanel(new BorderLayout());
    private PlayerPanel currectPlayerPanel = new PlayerPanel();
    
    //List of playerPanels
    private List<PlayerPanel> playerPanels = new ArrayList<>();
    
    public GamePanel(){
        
        cardLayout = new CardLayout();
        phases = new JPanel(cardLayout);
        
        //sets preferredSize, generated by Gemini
        phases.setPreferredSize(new Dimension(0, 0));
        playerPanelHolder.setPreferredSize(new Dimension(0, 0));

    
        //gridbaglayout for combining phasePanels and PlayerPanels
        setLayout(new GridBagLayout());
        GridBagConstraints gbc = new GridBagConstraints();
        //stretch horizontally and vertically, fill 100% of width
        gbc.fill = GridBagConstraints.BOTH;
        gbc.gridx = 0;
        gbc.weightx = 1;
        
        createPlayerPanels();
        
        phases.add(new BiddingPhasePanel(), "BIDDING");
        phases.add( new PlayPhasePanel(), "PLAYING");
        
        //adding phasePanels weighted
        gbc.gridy = 0;
        gbc.weighty = PHASE_PANEL_WEIGHT;
        add(phases, gbc);
        
        //add playerPanelHolder, weighted
        gbc.gridy++; //go down
        gbc.weighty = PLAYER_PANEL_WEIGHT;
        
        add(playerPanelHolder, gbc);
        
        displayCurrentPlayer();
        //show biddingPanel at first
        //cardLayout.show(phases, "BIDDING");
        
        
        cardLayout.show(phases, "PLAYING");
    }
    
    //generated by Gemini AI
    public void displayCurrentPlayer() {
        currectPlayerPanel = getCurrentPlayerPanel();
        if (currectPlayerPanel != null) {
            currectPlayerPanel.displayPlayer();
            
            playerPanelHolder.removeAll();
            playerPanelHolder.add(currectPlayerPanel, BorderLayout.CENTER);
            playerPanelHolder.revalidate();
            playerPanelHolder.repaint();
        }
    }
    
    //Create and add all the player panels to list
    public void createPlayerPanels(){
        playerPanels.add(new PlayerPanel(getGameInstance().getPlayerOne()));
        playerPanels.add(new PlayerPanel(getGameInstance().getPlayerTwo()));
        playerPanels.add(new PlayerPanel(getGameInstance().getPlayerThree()));
    }
    
    //return currentPlayerPanel's Panel
    public PlayerPanel getCurrentPlayerPanel(){
        
        PlayerPanel panelFound = null;
        for(int i = 0; i < playerPanels.size(); i++){
            //if the panelOwner at index is the same player as current owner
            if (playerPanels.get(i).getOwner().equals(getGameInstance().getCurrentPlayer()))
            {
                panelFound = playerPanels.get(i);
            }
        }
        
        return panelFound;
    }
    
}
