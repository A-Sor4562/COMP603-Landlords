package nz.ac.aut.bqw4562.landlords.app;

import javax.swing.JButton;
import nz.ac.aut.bqw4562.landlords.cards.Card;

/**
 *
 * @author AngelaSoriano
 */
public class CardButton extends JButton {
    private final Card card;
    private boolean isSelected = false;

    public CardButton(Card card) {
        this.card = card;
        
        //changes button text to card string
        setText(card.toString());
    }
    
    public Card getCard(){
        return card;
    }
    
    //for checking which cards are selected
    public boolean isSelectedCard(){
        return isSelected;
    }
    
    //Generated by gemini AI
    public void toggleSelection() {
        isSelected = !isSelected;
        // Visually highlight or shift the card when selected
        setBackground(isSelected ? java.awt.Color.YELLOW : null);
    }
}
